// Copies contract ABIs from the Foundry build into src/abi.ts so the backend and website stay in sync.
import fs from "node:fs";
const out = new URL("../../contracts/out/", import.meta.url);
const pick = (file, name) => JSON.parse(fs.readFileSync(new URL(`${file}/${name}.json`, out))).abi;
const abis = {
  launchpadAbi: pick("JustTagLaunchpad.sol", "JustTagLaunchpad"),
  tokenAbi: pick("JustTagToken.sol", "JustTagToken"),
  airdropAbi: pick("JustTagAirdrop.sol", "JustTagAirdrop"),
};
let ts = "// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.\n";
for (const [k, v] of Object.entries(abis)) ts += `export const ${k} = ${JSON.stringify(v)} as const;\n`;
fs.writeFileSync(new URL("../src/abi.ts", import.meta.url), ts);
fs.mkdirSync(new URL("../web/src/", import.meta.url), { recursive: true });
fs.writeFileSync(new URL("../web/src/abi.js", import.meta.url), ts.replaceAll(" as const", ""));
console.log("ABIs exported");
